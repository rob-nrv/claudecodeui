// CloudCLI's Claude Code statusLine bridge (FT-M07 Provider Live Usage).
//
// Claude Code hands its documented statusLine JSON — including
// `rate_limits.five_hour` and `rate_limits.seven_day` — to the configured
// statusLine command on stdin, in interactive sessions. The bridge is a small
// standalone Node script that records those two windows into the Claude config
// directory that produced them, then hands the very same stdin to the status
// line command the user had before (if any), so what they see is unchanged.
//
// This file only holds pure logic: the script source, how its command line is
// built and recognized, and how settings.json is rewritten to install or remove
// it. All filesystem work lives in claude-live-usage.service.ts.
import { AppError } from '@/shared/utils.js';

/** Bumped whenever the script source changes, so earlier installs report `outdated`. */
export const CLAUDE_STATUSLINE_BRIDGE_VERSION = 1;

export const CLAUDE_STATUSLINE_BRIDGE_FILE_NAME = 'claude-statusline-bridge.mjs';

/** Written by the bridge inside the Claude config directory whose settings launched it. */
export const CLAUDE_LIVE_USAGE_SNAPSHOT_FILE_NAME = 'cloudcli-live-usage.json';

const BRIDGE_MARKER_FLAG = '--cloudcli-statusline-bridge=';
const WRAP_FLAG = '--wrap=';

/** Characters that change meaning inside a double-quoted word in sh/bash/zsh or PowerShell. */
const UNSAFE_SHELL_WORD_CHARACTERS = /["$`\\\r\n]/;

/**
 * Source of the bridge script, written verbatim to disk by the live-usage
 * service. Node built-ins only, no `${` or backticks inside (it is a raw
 * template), and it never prints or stores anything beyond the two windows.
 */
export const CLAUDE_STATUSLINE_BRIDGE_SCRIPT = String.raw`// CloudCLI Claude Code statusLine bridge v1. Generated by CloudCLI.
// Records rate_limits.five_hour and rate_limits.seven_day from Claude Code's
// statusLine JSON into the Claude config directory that produced them, then
// runs the status line command configured before CloudCLI (if any) with the
// same input. Disable live usage for the account in CloudCLI to restore it.
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const SNAPSHOT_FILE_NAME = 'cloudcli-live-usage.json';
const WRAP_FLAG = '--wrap=';
const MAX_INPUT_BYTES = 1048576;

function readInput() {
  return new Promise((resolve) => {
    const chunks = [];
    let total = 0;
    process.stdin.on('data', (chunk) => {
      total += chunk.length;
      if (total <= MAX_INPUT_BYTES) chunks.push(chunk);
    });
    process.stdin.on('end', () => resolve(Buffer.concat(chunks)));
    process.stdin.on('error', () => resolve(Buffer.concat(chunks)));
  });
}

function readWindow(value) {
  if (!value || typeof value !== 'object') return null;
  const used = value.used_percentage;
  const resetsAt = value.resets_at;
  if (typeof used !== 'number' || !Number.isFinite(used)) return null;
  if (typeof resetsAt !== 'number' || !Number.isFinite(resetsAt)) return null;
  return { used_percentage: used, resets_at: resetsAt };
}

function captureSnapshot(input) {
  let payload;
  try {
    payload = JSON.parse(input.toString('utf8'));
  } catch {
    return null;
  }
  const limits = payload && typeof payload === 'object' ? payload.rate_limits : null;
  // Absent before the first response (and for accounts without limits):
  // nothing was observed in this update, so the last snapshot is left alone.
  if (!limits || typeof limits !== 'object') return null;
  const fiveHour = readWindow(limits.five_hour);
  const sevenDay = readWindow(limits.seven_day);
  if (!fiveHour && !sevenDay) return null;

  const configured = (process.env.CLAUDE_CONFIG_DIR || '').trim();
  const configDirectory = configured ? path.resolve(configured) : path.join(os.homedir(), '.claude');
  const rateLimits = {};
  if (fiveHour) rateLimits.five_hour = fiveHour;
  if (sevenDay) rateLimits.seven_day = sevenDay;
  const snapshot = {
    schemaVersion: 1,
    source: 'claude-statusline',
    configDirectory,
    capturedAt: Date.now(),
    rateLimits,
  };

  const target = path.join(configDirectory, SNAPSHOT_FILE_NAME);
  const temporary = target + '.' + process.pid + '.tmp';
  try {
    fs.writeFileSync(temporary, JSON.stringify(snapshot), { mode: 0o600 });
    fs.renameSync(temporary, target);
  } catch {
    try { fs.unlinkSync(temporary); } catch {}
  }
  return snapshot;
}

function readWrappedCommand(args) {
  const flag = args.find((argument) => argument.startsWith(WRAP_FLAG));
  if (!flag) return null;
  try {
    const decoded = JSON.parse(Buffer.from(flag.slice(WRAP_FLAG.length), 'base64url').toString('utf8'));
    return decoded && typeof decoded.command === 'string' && decoded.command.trim() ? decoded.command : null;
  } catch {
    return null;
  }
}

// Claude Code runs status line commands on Windows through Git Bash when it is
// installed, otherwise through PowerShell; the wrapped command gets the same.
function findGitBash() {
  const candidates = [];
  if (process.env.CLAUDE_CODE_GIT_BASH_PATH) candidates.push(process.env.CLAUDE_CODE_GIT_BASH_PATH);
  const pathValue = process.env.PATH || process.env.Path || '';
  for (const entry of pathValue.split(path.delimiter)) {
    if (!entry) continue;
    try {
      if (!fs.statSync(path.join(entry, 'git.exe')).isFile()) continue;
    } catch {
      continue;
    }
    const folder = path.basename(entry).toLowerCase();
    const gitRoot = folder === 'cmd' || folder === 'bin' ? path.dirname(entry) : entry;
    candidates.push(path.join(gitRoot, 'bin', 'bash.exe'));
  }
  for (const base of [process.env.ProgramFiles, process.env['ProgramFiles(x86)']]) {
    if (base) candidates.push(path.join(base, 'Git', 'bin', 'bash.exe'));
  }
  return candidates.find((candidate) => {
    try {
      return fs.statSync(candidate).isFile();
    } catch {
      return false;
    }
  }) || null;
}

function runWrapped(command, input) {
  return new Promise((resolve) => {
    let child;
    const stdio = ['pipe', 'inherit', 'inherit'];
    try {
      if (process.platform === 'win32') {
        const gitBash = findGitBash();
        child = gitBash
          ? spawn(gitBash, ['-c', command], { stdio, windowsHide: true })
          : spawn('powershell.exe', ['-NoProfile', '-Command', command], { stdio, windowsHide: true });
      } else {
        child = spawn(command, { shell: true, stdio });
      }
    } catch {
      resolve(1);
      return;
    }
    const stop = () => {
      try { child.kill(); } catch {}
    };
    process.once('SIGTERM', stop);
    process.once('SIGINT', stop);
    child.on('error', () => resolve(1));
    child.on('close', (code) => resolve(typeof code === 'number' ? code : 1));
    child.stdin.on('error', () => {});
    child.stdin.end(input);
  });
}

function formatOwnLine(snapshot) {
  if (!snapshot) return '';
  const parts = [];
  if (snapshot.rateLimits.five_hour) parts.push('5h ' + Math.round(snapshot.rateLimits.five_hour.used_percentage) + '%');
  if (snapshot.rateLimits.seven_day) parts.push('7d ' + Math.round(snapshot.rateLimits.seven_day.used_percentage) + '%');
  return parts.join(' | ');
}

const input = await readInput();
let snapshot = null;
try {
  snapshot = captureSnapshot(input);
} catch {
  snapshot = null;
}
const wrappedCommand = readWrappedCommand(process.argv.slice(2));
if (wrappedCommand) {
  process.exitCode = await runWrapped(wrappedCommand, input);
} else {
  const line = formatOwnLine(snapshot);
  if (line) process.stdout.write(line + '\n');
}
`;

type ClaudeSettings = Record<string, unknown>;

type UserStatusLine = Record<string, unknown> & { type: 'command'; command: string };

type StatusLineRead =
  | { kind: 'absent' }
  | { kind: 'command'; statusLine: UserStatusLine }
  | { kind: 'unrecognized' };

type ParsedBridgeCommand = {
  version: number;
  wrappedCommand: string | null;
  /** False when a wrap flag is present but cannot be decoded: never treat that as "wraps nothing". */
  wrapReadable: boolean;
};

const isPlainObject = (value: unknown): value is Record<string, unknown> =>
  Boolean(value) && typeof value === 'object' && !Array.isArray(value);

const encodeWrappedCommand = (command: string): string =>
  Buffer.from(JSON.stringify({ command }), 'utf8').toString('base64url');

function toQuotedShellWord(value: string, platform: NodeJS.Platform): string {
  // Git Bash strips unquoted backslashes, so Windows paths use forward slashes.
  const normalized = platform === 'win32' ? value.replace(/\\/g, '/') : value;
  if (!normalized || UNSAFE_SHELL_WORD_CHARACTERS.test(normalized)) {
    throw new AppError('The live usage bridge path cannot be placed safely in a status line command.', {
      code: 'LIVE_USAGE_COMMAND_UNSAFE',
      statusCode: 409,
    });
  }
  return `"${normalized}"`;
}

function readStatusLine(settings: ClaudeSettings): StatusLineRead {
  if (settings.statusLine === undefined) {
    return { kind: 'absent' };
  }
  const value = settings.statusLine;
  if (isPlainObject(value) && value.type === 'command' && typeof value.command === 'string') {
    return { kind: 'command', statusLine: value as UserStatusLine };
  }
  return { kind: 'unrecognized' };
}

/**
 * Builds the statusLine `command` that runs the bridge. On Windows the command
 * may run through Git Bash or PowerShell, which disagree on invoking a quoted
 * executable path, so `node` is resolved from PATH there; elsewhere the exact
 * Node binary running CloudCLI is used. A wrapped user command travels as
 * base64url, which holds no shell metacharacters in any of those shells.
 *
 * Consumed by the live-usage service when installing, and by its tests.
 */
export function buildStatusLineBridgeCommand(input: {
  platform: NodeJS.Platform;
  nodeExecutablePath: string;
  scriptPath: string;
  wrappedCommand: string | null;
}): string {
  const nodeWord = input.platform === 'win32' ? 'node' : toQuotedShellWord(input.nodeExecutablePath, input.platform);
  const words = [
    nodeWord,
    toQuotedShellWord(input.scriptPath, input.platform),
    `${BRIDGE_MARKER_FLAG}${CLAUDE_STATUSLINE_BRIDGE_VERSION}`,
  ];
  if (input.wrappedCommand !== null) {
    words.push(`${WRAP_FLAG}${encodeWrappedCommand(input.wrappedCommand)}`);
  }
  return words.join(' ');
}

/**
 * Recognizes a bridge command written by any CloudCLI version, or returns null
 * for every other command (which is then always the user's own).
 */
export function parseStatusLineBridgeCommand(command: string): ParsedBridgeCommand | null {
  if (!command.includes(CLAUDE_STATUSLINE_BRIDGE_FILE_NAME)) {
    return null;
  }
  const words = command.split(/\s+/);
  const marker = words.find((word) => word.startsWith(BRIDGE_MARKER_FLAG));
  if (!marker) {
    return null;
  }
  const version = Number.parseInt(marker.slice(BRIDGE_MARKER_FLAG.length), 10);
  if (!Number.isInteger(version)) {
    return null;
  }

  const wrapWord = words.find((word) => word.startsWith(WRAP_FLAG));
  if (!wrapWord) {
    return { version, wrappedCommand: null, wrapReadable: true };
  }
  try {
    const decoded: unknown = JSON.parse(Buffer.from(wrapWord.slice(WRAP_FLAG.length), 'base64url').toString('utf8'));
    if (isPlainObject(decoded) && typeof decoded.command === 'string') {
      return { version, wrappedCommand: decoded.command, wrapReadable: true };
    }
  } catch {
    // Falls through to the unreadable result below.
  }
  return { version, wrappedCommand: null, wrapReadable: false };
}

/**
 * Describes what settings.json currently holds, without changing anything.
 * Consumed by the live-usage service to report the bridge state.
 */
export function inspectStatusLineBridge(settings: ClaudeSettings): {
  installedVersion: number | null;
  wrapsExistingStatusLine: boolean;
  hasUserStatusLine: boolean;
} {
  const current = readStatusLine(settings);
  if (current.kind !== 'command') {
    return { installedVersion: null, wrapsExistingStatusLine: false, hasUserStatusLine: current.kind === 'unrecognized' };
  }
  const parsed = parseStatusLineBridgeCommand(current.statusLine.command);
  if (!parsed) {
    return { installedVersion: null, wrapsExistingStatusLine: false, hasUserStatusLine: true };
  }
  return {
    installedVersion: parsed.version,
    wrapsExistingStatusLine: parsed.wrappedCommand !== null || !parsed.wrapReadable,
    hasUserStatusLine: false,
  };
}

const refuseUnreadableWrap = (): never => {
  throw new AppError('The installed usage bridge wraps a status line command CloudCLI can no longer read, so it will not change it.', {
    code: 'LIVE_USAGE_BRIDGE_WRAP_UNREADABLE',
    statusCode: 409,
  });
};

/**
 * Returns settings with the bridge installed. Every other key is preserved, and
 * so is every other field of an existing statusLine (padding, refreshInterval,
 * ...). An existing user command is wrapped, never dropped; installing over an
 * existing bridge keeps the command it already wraps instead of wrapping the
 * bridge inside itself. A statusLine CloudCLI cannot interpret is refused.
 *
 * Consumed by the live-usage service when enabling live usage.
 */
export function planStatusLineBridgeInstall(
  settings: ClaudeSettings,
  buildCommand: (wrappedCommand: string | null) => string,
): ClaudeSettings {
  const current = readStatusLine(settings);
  if (current.kind === 'unrecognized') {
    throw new AppError('This account has a statusLine setting CloudCLI does not recognize, so it will not change it.', {
      code: 'LIVE_USAGE_STATUSLINE_UNRECOGNIZED',
      statusCode: 409,
    });
  }
  if (current.kind === 'absent') {
    return { ...settings, statusLine: { type: 'command', command: buildCommand(null) } };
  }

  const parsed = parseStatusLineBridgeCommand(current.statusLine.command);
  if (parsed && !parsed.wrapReadable) {
    refuseUnreadableWrap();
  }
  const wrappedCommand = parsed ? parsed.wrappedCommand : current.statusLine.command;
  return { ...settings, statusLine: { ...current.statusLine, command: buildCommand(wrappedCommand) } };
}

/**
 * Returns settings with the bridge removed and the user's original statusLine
 * restored exactly, or null when no CloudCLI bridge is installed — a statusLine
 * CloudCLI did not write is never touched.
 *
 * Consumed by the live-usage service when disabling live usage.
 */
export function planStatusLineBridgeRemoval(settings: ClaudeSettings): ClaudeSettings | null {
  const current = readStatusLine(settings);
  if (current.kind !== 'command') {
    return null;
  }
  const parsed = parseStatusLineBridgeCommand(current.statusLine.command);
  if (!parsed) {
    return null;
  }
  if (!parsed.wrapReadable) {
    refuseUnreadableWrap();
  }
  if (parsed.wrappedCommand === null) {
    const withoutStatusLine = { ...settings };
    delete withoutStatusLine.statusLine;
    return withoutStatusLine;
  }
  return { ...settings, statusLine: { ...current.statusLine, command: parsed.wrappedCommand } };
}
